IconData faIcon(String? name) {
  if (name == null || name.isEmpty) return FontAwesomeIcons.circle;
  final n = name.startsWith('fa-') ? name : 'fa-$name';
  return _faMap[n] ?? FontAwesomeIcons.circle;
}

/// Small helper to render a Font Awesome icon by web class name.
class Fa extends StatelessWidget {
  const Fa(this.name, {super.key, this.size = 14, this.color});
  final String name;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) => FaIcon(faIcon(name), size: size, color: color);
}
